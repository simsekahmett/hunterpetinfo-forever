#!/usr/bin/env python3
"""Builds ForeverHunterPetInfo's generated data files (Data/Beasts.lua, Data/BeastNames.lua).

Sources (nothing is needed at runtime):
  * QuestieDB/QuestieDB_Camelot.toc, from a WoW Forever AddOns folder
      -> each beast's name, level, zone, position and localized names
  * ClassicHunterPetInfo/Vanilla/pet_information.lua, pet_abilities.lua
      -> which NPCs are tameable, their family, attack speed and the
         abilities they teach, as they were in Classic
  * ForeverHunterPetInfo/Data/Families.lua
      -> the abilities a family can learn in Forever

Usage: gen_data.py <Forever AddOns dir> <ClassicHunterPetInfo dir> <output Data dir>
Requires: pip install cbor2
"""
import base64
import re
import sys
import zlib
from pathlib import Path

import cbor2

addons = Path(sys.argv[1])
classic_dir = Path(sys.argv[2])
out = Path(sys.argv[3])

HEADER = "-- GENERATED by tools/gen_data.py. Do not edit, run the tool again.\n"

# ---------------------------------------------------------------- Families

families_text = (out / "Families.lua").read_text(encoding="utf-8")
family_abilities = {}
for m in re.finditer(r"\[(['\"])(.+?)\1\] = \{ icon = .*?abilities = \{(.*?)\} \}", families_text):
    family_abilities[m.group(2)] = re.findall(r"'([^']*)'|\"([^\"]*)\"", m.group(3))
family_abilities = {k: [a or b for a, b in v] for k, v in family_abilities.items()}
if len(family_abilities) != 18:
    raise SystemExit(f"expected 18 families, found {len(family_abilities)}")

FAMILY_RENAMES = {"Owl": "Bird of Prey"}
# Abilities that were renamed, per family; one that a family lost is dropped
ABILITY_RENAMES = {("Carrion Bird", "Screech"): "Demoralizing Screech"}

# ------------------------------------------------------------------ Classic

info_text = (classic_dir / "Vanilla/pet_information.lua").read_text(encoding="utf-8")
ability_text = (classic_dir / "Vanilla/pet_abilities.lua").read_text(encoding="utf-8")
# The test value at the top of the abilities is commented out
ability_text = re.sub(r"--\[\[.*?\]\]", "", ability_text, flags=re.S)

classic = {}
for m in re.finditer(
        r'\[(\d+)\] = \{\s*\["attack_speed"\] = ([\d.]+),\s*\["name"\] = "([^"]*)",\s*'
        r'\["family"\] = "([^"]*)",\s*\["min_level"\] = (\d+),\s*\["max_level"\] = (\d+),\s*'
        r'\["area"\] = "([^"]*)"', info_text):
    npc, speed, name, family, low, high, area = m.groups()
    family = FAMILY_RENAMES.get(family, family)
    if family not in family_abilities:
        raise SystemExit(f"unknown family {family} for NPC {npc}")
    speed = float(speed)
    classic[int(npc)] = {
        "name": name, "family": family, "min": int(low), "max": int(high), "area": area,
        # 999 stands for an unknown speed
        "speed": 0 if speed >= 999 else speed, "abilities": [],
    }

dropped = {}
for m in re.finditer(r"\[(\d+)\] = \{((?:\s*\{[^{}]*\},?)+)\s*\}", ability_text):
    npc = int(m.group(1))
    if npc not in classic:
        continue
    family = classic[npc]["family"]
    for ability, rank in re.findall(r'\["ability"\] = "([^"]*)",\s*\["rank"\] = (\d+)', m.group(2)):
        ability = ABILITY_RENAMES.get((family, ability), ability)
        if ability in family_abilities[family]:
            classic[npc]["abilities"].append((ability, int(rank)))
        else:
            dropped[(family, ability)] = dropped.get((family, ability), 0) + 1

# ----------------------------------------------------------------- Questie

meta = {}
with open(addons / "QuestieDB/QuestieDB_Camelot.toc", encoding="utf-8") as f:
    for line in f:
        if line.startswith("## X-"):
            key, _, value = line[3:].rstrip("\n").partition(": ")
            meta[key] = value


def stored(key):
    value = meta.get(key)
    if value is None:
        return None
    m = re.fullmatch(r"~(\d+)~", value)
    if m:
        value = "".join(meta[f"{key}-{i}"] for i in range(1, int(m.group(1)) + 1))
    return value


def decode(key, compressed=False):
    value = stored(key)
    if value is None:
        return None
    raw = base64.b64decode(value)
    if compressed:
        raw = zlib.decompress(raw)
    return cbor2.loads(raw)


def txt(value):
    return value.decode("utf-8") if isinstance(value, bytes) else (value or "")


def as_row(value):
    """Returns a stored row as a table of field indices."""
    if isinstance(value, list):
        return {i + 1: v for i, v in enumerate(value)}
    return value or {}


NPC_NAME, NPC_MIN_LEVEL, NPC_MAX_LEVEL, NPC_SPAWNS, NPC_ZONE = 1, 4, 5, 7, 9

npc_id_list = decode("X-Npc-IDS", compressed=True)
npc_ids = set(npc_id_list)

beasts = {}
missing = []
for npc in sorted(classic):
    beast = classic[npc]
    if npc not in npc_ids:
        # Not an NPC of Forever, as far as Questie knows
        missing.append(f"{npc} {beast['name']}")
        continue

    row = as_row(decode(f"X-Npc-{npc}-S"))
    spawns = decode(f"X-Npc-{npc}-{NPC_SPAWNS}") or {}
    if isinstance(spawns, list):  # a Lua array, i.e. zone IDs 1..n
        spawns = {i + 1: v for i, v in enumerate(spawns) if v}
    spawns = {z: v for z, v in spawns.items() if isinstance(v, list) and v}

    zone = row.get(NPC_ZONE) or 0
    if (not zone or zone not in spawns) and spawns:
        zone = max(spawns, key=lambda z: len(spawns[z]))
    x = y = -1
    points = spawns.get(zone)
    if points and isinstance(points[0], list) and points[0][0] is not None and points[0][0] >= 0:
        x, y = points[0][0], points[0][1]

    low, high = row.get(NPC_MIN_LEVEL) or 0, row.get(NPC_MAX_LEVEL) or 0
    if not low:
        low, high = beast["min"], beast["max"]

    beasts[npc] = {
        "name": txt(row.get(NPC_NAME)) or beast["name"], "family": beast["family"],
        "min": low, "max": max(low, high), "zone": zone if zone > 0 else 0, "x": x, "y": y,
        "speed": beast["speed"], "abilities": beast["abilities"],
        # Instances have no area of their own in the data, the Classic name stands in
        "area": "" if zone > 0 else beast["area"],
    }

# Localized names: one compressed column block per locale, aligned with the ID list
LOCALES = ["deDE", "esES", "esMX", "frFR", "koKR", "ptBR", "ruRU", "zhCN", "zhTW"]
names = {}
for locale in LOCALES:
    localized = {}
    blk = decode(f"X-l10n-{locale}-Npc", compressed=True)
    if blk is not None:
        for index, name in enumerate(blk[0]):
            npc = npc_id_list[index]
            if npc in beasts and name and txt(name) != beasts[npc]["name"]:
                localized[npc] = txt(name)
    names[locale] = localized

# ------------------------------------------------------------------ Output


def lua_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def num(v):
    return str(int(v)) if float(v).is_integer() else f"{v:.1f}"


with open(out / "Beasts.lua", "w", encoding="utf-8", newline="\n") as f:
    f.write(HEADER)
    f.write("-- Names, levels, zones and positions derived from QuestieDB; families, attack\n"
            "-- speeds and abilities from Classic data. See NOTICE.md.\n")
    f.write("local _, ns = ...\n\n")
    f.write("-- [npcId] = { name (enUS), family, minLevel, maxLevel, areaId, x, y,\n"
            "--             seconds between attacks (0 if unknown),\n"
            "--             { ability, rank, ... } or nil, area name if it has no areaId }\n")
    f.write("ns.Data.beasts = {\n")
    for npc in sorted(beasts):
        b = beasts[npc]
        abilities = "nil"
        if b["abilities"]:
            abilities = "{" + ",".join(f"{lua_str(a)},{r}" for a, r in b["abilities"]) + "}"
        fields = [lua_str(b["name"]), lua_str(b["family"]), str(b["min"]), str(b["max"]), str(b["zone"]),
                  num(b["x"]), num(b["y"]), num(b["speed"]), abilities]
        if b["area"]:
            fields.append(lua_str(b["area"]))
        elif abilities == "nil":
            fields.pop()
        f.write(f"[{npc}]={{{','.join(fields)}}},\n")
    f.write("}\n")

with open(out / "BeastNames.lua", "w", encoding="utf-8", newline="\n") as f:
    f.write(HEADER)
    f.write("-- Localized beast names derived from QuestieDB, see NOTICE.md.\n")
    f.write("local _, ns = ...\n\nlocal locale = GetLocale()\n")
    for locale in LOCALES:
        if not names[locale]:
            continue
        f.write(f"\nif locale == '{locale}' then\nns.Data.beastNames = {{\n")
        for npc in sorted(names[locale]):
            f.write(f"[{npc}]={lua_str(names[locale][npc])},\n")
        f.write("}\nend\n")

print(f"beasts: {len(beasts)} of {len(classic)} Classic ones")
print(f"with abilities: {sum(1 for b in beasts.values() if b['abilities'])}; "
      f"with a known speed: {sum(1 for b in beasts.values() if b['speed'])}; "
      f"without a zone: {sum(1 for b in beasts.values() if not b['zone'])}")
print("not in Forever: " + (", ".join(missing) or "none"))
print("abilities dropped: " + ", ".join(f"{f} {a} x{n}" for (f, a), n in sorted(dropped.items())))
print("localized: " + ", ".join(f"{k}={len(v)}" for k, v in names.items()))
